func fullPullPage(updated, merged time.Time) []map[string]any {
	page := make([]map[string]any, perPage)
	for i := range page {
		page[i] = map[string]any{
			"created_at": merged.Add(-time.Hour).Format(time.RFC3339),
			"updated_at": updated.Format(time.RFC3339),
			"merged_at":  merged.Format(time.RFC3339),
			"body":       "human",
		}
	}
	return page
}

